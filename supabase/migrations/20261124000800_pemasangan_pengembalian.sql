-- ID memakai "by default" supaya bisa dipesan lebih dulu (reservasi) untuk path foto.
create table public.pemasangan (
  id              bigint generated by default as identity primary key,
  peminjaman_id   bigint not null unique references public.peminjaman (id) on delete cascade,
  staff_id        uuid not null references public.staff_it (id) on delete restrict,
  tgl_pemasangan  timestamptz not null default now(),
  created_at      timestamptz not null default now()
);
create index pemasangan_staff_idx on public.pemasangan (staff_id);

create table public.pengembalian (
  id              bigint generated by default as identity primary key,
  peminjaman_id   bigint not null unique references public.peminjaman (id) on delete cascade,
  staff_id        uuid not null references public.staff_it (id) on delete restrict,
  tgl_kembali     timestamptz not null default now(),
  created_at      timestamptz not null default now()
);
create index pengembalian_staff_idx on public.pengembalian (staff_id);

create table public.foto_pemasangan (
  id             bigint generated always as identity primary key,
  pemasangan_id  bigint not null references public.pemasangan (id) on delete cascade,
  path_foto      text not null unique,
  created_at     timestamptz not null default now()
);
create index foto_pemasangan_pemasangan_idx on public.foto_pemasangan (pemasangan_id);

create table public.foto_pengembalian (
  id               bigint generated always as identity primary key,
  pengembalian_id  bigint not null references public.pengembalian (id) on delete cascade,
  path_foto        text not null unique,
  created_at       timestamptz not null default now()
);
create index foto_pengembalian_pengembalian_idx on public.foto_pengembalian (pengembalian_id);

-- Penggantian unit saat pemasangan (unit gagal dites).
create table public.penggantian_unit (
  id                    bigint generated always as identity primary key,
  detail_peminjaman_id  bigint not null references public.detail_peminjaman (id) on delete cascade,
  aset_lama_id          bigint not null references public.aset (id) on delete restrict,
  aset_baru_id          bigint not null references public.aset (id) on delete restrict,
  alasan                text not null check (length(trim(alasan)) > 0),
  staff_id              uuid references public.staff_it (id) on delete set null,
  created_at            timestamptz not null default now()
);
create index penggantian_unit_detail_idx on public.penggantian_unit (detail_peminjaman_id);
create index penggantian_unit_aset_lama_idx on public.penggantian_unit (aset_lama_id);
create index penggantian_unit_aset_baru_idx on public.penggantian_unit (aset_baru_id);

-- Aset yang pernah diganti juga dianggap punya riwayat (tidak boleh dihapus).
create or replace function public.guard_hapus_aset()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if exists (select 1 from public.detail_peminjaman where aset_id = old.id)
     or exists (select 1 from public.penggantian_unit where aset_lama_id = old.id or aset_baru_id = old.id) then
    raise exception 'Aset % memiliki riwayat peminjaman dan tidak dapat dihapus.', old.kode_aset
      using errcode = 'P0001';
  end if;
  return old;
end;
$$;

